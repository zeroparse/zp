package tsgen

import (
	"fmt"
	"io/fs"
	"reflect"
	"regexp"
	"strings"
	"sync"

	"zeroparse.dev/zp/internal/codegen"
)

// The TypeScript library of generated parsers is the directory codegen/ts/lib of this module, which
// TypeScript generation reads from GenOptions.TSLib: lib.ts, the library proper, and the modules
// that the generator places after it (libModules). Generation assembles them into one module, the
// lib.ts that parsers import.

// libModules are the files of the library that follow lib.ts in the generated module, with the
// heading that introduces each.
var libModules = []struct{ file, heading string }{
	{"budget.ts", "Invocation limit controls"},
	{"trace.ts", "Tracing"},
	{"profile.ts", "Profiling"},
}

// tsExportDecl matches an exported declaration of the library.
var tsExportDecl = regexp.MustCompile(`(?m)^export (?:abstract )?(function|class|const|let|interface|type) ([\p{L}\p{N}_$]+)`)

// tsLib is an assembled library: the text of the generated lib.ts and its exported names, mapped to
// whether they are only types.
type tsLib struct {
	text    string
	exports map[string]bool
}

// libCache memoizes the assembled library of each source, keyed as gogen keys its library cache:
// only a source whose dynamic type is a string or a pointer is a valid map key.
var libCache struct {
	mu  sync.Mutex
	lib map[fs.FS]*tsLib
}

// loadLib assembles the library of fsys (once per source).
func loadLib(fsys fs.FS) (*tsLib, error) {
	if fsys == nil {
		return nil, fmt.Errorf("TypeScript generation needs the library source: set GenOptions.TSLib")
	}
	k := reflect.TypeOf(fsys).Kind()
	cacheable := k == reflect.String || k == reflect.Pointer
	libCache.mu.Lock()
	defer libCache.mu.Unlock()
	if cacheable {
		if lib, ok := libCache.lib[fsys]; ok {
			return lib, nil
		}
	}
	lib, err := assembleLib(fsys)
	if err != nil {
		return nil, err
	}
	if cacheable {
		if libCache.lib == nil {
			libCache.lib = map[fs.FS]*tsLib{}
		}
		libCache.lib[fsys] = lib
	}
	return lib, nil
}

// assembleLib returns the generated lib.ts of the library in fsys: lib.ts after its marker, with the
// printed methods substituted, followed by libModules, and the exported names of the result.
func assembleLib(fsys fs.FS) (*tsLib, error) {
	read := func(name string) (string, error) {
		data, err := fs.ReadFile(fsys, name)
		return string(data), err
	}
	src, err := read(tsLibFileName)
	if err != nil {
		return nil, err
	}
	ms, err := tsMethods()
	if err != nil {
		return nil, err
	}
	src = substituteMethods(src, ms)
	i := strings.Index(src, tsLibMarker)
	if i < 0 {
		return nil, fmt.Errorf("the TypeScript library's %s has no marker %q", tsLibFileName, strings.TrimSpace(tsLibMarker))
	}
	var b strings.Builder
	b.WriteString(TsGeneratedHeader())
	b.WriteString("// The library of the TypeScript parsers generated by zp: nodes, errors, the parsing machine and\n")
	b.WriteString("// the controls of an invocation. It does not depend on a grammar; every parser imports it.\n\n")
	b.WriteString("/* eslint-disable */\n\n")
	b.WriteString(src[i+len(tsLibMarker):])
	for _, m := range libModules {
		text, err := read(m.file)
		if err != nil {
			return nil, err
		}
		b.WriteString("\n// --- " + m.heading + " ---\n")
		b.WriteString(text)
	}
	lib := &tsLib{text: b.String(), exports: map[string]bool{}}
	for _, m := range tsExportDecl.FindAllStringSubmatch(lib.text, -1) {
		// An interface merged with a class of the same name is a value.
		isType := m[1] == "interface" || m[1] == "type"
		if prev, ok := lib.exports[m[2]]; ok {
			isType = isType && prev
		}
		lib.exports[m[2]] = isType
	}
	return lib, nil
}

// LibText returns the text of the generated lib.ts of the library in fsys.
func LibText(fsys fs.FS) (string, error) {
	lib, err := loadLib(fsys)
	if err != nil {
		return "", err
	}
	return lib.text, nil
}

// LibFiles returns the file of the library alone, as LibOnly generates it.
func LibFiles(fsys fs.FS) ([]codegen.GeneratedFile, error) {
	text, err := LibText(fsys)
	if err != nil {
		return nil, err
	}
	return []codegen.GeneratedFile{{Path: tsLibFileName, Content: []byte(text)}}, nil
}
