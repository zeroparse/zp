package codegentest

import (
	"os"
	"strings"
)

// SetGoFlags sets the GOFLAGS of the test process, which the go commands it runs inherit, for
// building generated programs: -trimpath, so that their builds in fresh temporary directories share
// the build cache, -mod=mod, so that the temporary modules that replace this module resolve it
// without a go.sum, and the tag zp_feature_witness, so that every generated parser checks that its
// parses use only the library features that the generator's analysis found
// (codegen.GenOptions.FeatureWitness).
func SetGoFlags() {
	os.Setenv("GOFLAGS", strings.TrimSpace(os.Getenv("GOFLAGS")+" "+GoFlags))
}

// GoFlags are the flags that SetGoFlags adds, for a go command that sets its GOFLAGS itself
// (GoFlagsEnv).
const GoFlags = "-trimpath -mod=mod " + WitnessTags

// WitnessTags is the build flag that turns on the check of the features of the generated parsers
// (codegen.GenOptions.FeatureWitness), which every build of a parser generated by these helpers
// needs.
const WitnessTags = "-tags=zp_feature_witness"

// GoFlagsEnv is the GOFLAGS entry of the environment of a go command that builds generated programs.
const GoFlagsEnv = "GOFLAGS=" + GoFlags

// SetGoCache points the build cache of the go commands that the test process runs at a fresh
// temporary directory and returns a function that removes it. Every test builds a different
// generated program, so the shared build cache would only accumulate entries that are never reused;
// a cache private to the test process still shares the builds of the standard library and of this
// module among the tests of a package.
func SetGoCache() (remove func()) {
	dir, err := os.MkdirTemp("", "zp-gocache-")
	if err != nil {
		panic(err)
	}
	os.Setenv("GOCACHE", dir)
	return func() { os.RemoveAll(dir) }
}
