// placed is a package's place in the release layout.
type placed struct {
	target    string
	generated bool
	row       int // index of the layout row
}

// placeOf places the package at the module-relative path rel.
func placeOf(rel string) (placed, error) {
	best, bestLen := -1, -1
	var target string
	for i, p := range layout {
		base, tree := strings.CutSuffix(p.pkg, "/...")
		var t string
		switch {
		case rel == base:
			t = p.target
		case tree && strings.HasPrefix(rel, base+"/"):
			t = p.target + rel[len(base):]
		default:
			continue
		}
		n := len(base)
		if !tree {
			n++ // an exact row wins over a tree row of the same path
		}
		if n > bestLen {
			best, bestLen, target = i, n, t
		}
	}
	if best < 0 {
		return placed{}, fmt.Errorf("%s: no row of layout places the package; add one at its path in the release layout", rel)
	}
	return placed{target: target, generated: layout[best].generated, row: best}, nil
}

// under reports whether the layout path t is dir or below it.
func under(t, dir string) bool {
	return t == dir || strings.HasPrefix(t, dir+"/")
}

// runtimeSide reports whether the layout path t is on the runtime side.
func runtimeSide(t string) bool {
	return under(t, "pkg/runtime") || under(t, "pkg/bytecode") || under(t, "internal/runtime")
}

// publicRuntime reports whether t is a public package of the runtime side, where the chains of
// rule 1 start.
func publicRuntime(t string) bool {
	return under(t, "pkg/runtime") || under(t, "pkg/bytecode")
}

// golib is the layout path of the library of generated Go parsers.
const golib = "pkg/runtime/golib"

// libraryImport reports whether the library of generated Go parsers may import the package at
// the layout path t.
func libraryImport(t string) bool {
	switch t {
	case "pkg/runtime", "pkg/runtime/input", "pkg/runtime/value", "pkg/runtime/value/impl",
		"pkg/runtime/instrument", "pkg/runtime/schema":
		return true
	}
	return false
}

// engineSide reports whether t is a package that a generated parser must not link: the VM or
// the internal runtime.
func engineSide(t string) bool {
	return under(t, "pkg/runtime/vm") || under(t, "internal/runtime")
}

// layer2 reports the rule 2 clauses that an import of the package at layout path b by the
// package at layout path a breaks.
func layer2(a, b string) []string {
	if a == b {
		return nil
	}
	var broken []string
	if under(a, "internal/pass") && !under(b, "internal/pass") {
		broken = append(broken, "internal/pass imports nothing of the module")
	}
	if under(a, "internal/ir") {
		if !under(b, "internal/ir") && !under(b, "internal/pass") && !under(b, "internal/cancel") && b != "pkg/grammar/ast" {
			broken = append(broken, "internal/ir/** imports only internal/ir/**, internal/pass, internal/cancel and pkg/grammar/ast")
		} else if under(b, "internal/ir") {
			if c := dialect(a, b); c != "" {
				broken = append(broken, c)
			}
		}
	}
	if la, lb := layerOf(a), layerOf(b); la != layerRuntime && la != lb && !layerImports(la, lb) {
		broken = append(broken, fmt.Sprintf("the %s layer does not import the %s layer", la, lb))
	}
	if under(b, "internal/lsp") && !under(a, "internal/lsp") && !under(a, "cmd") && !under(a, "internal/testing") {
		broken = append(broken, "only cmd/** and internal/testing/** import internal/lsp/**")
	}
	if under(b, "internal/testing") && !under(a, "internal/testing") {
		broken = append(broken, "only internal/testing/** imports internal/testing/** outside tests")
	}
	return broken
}

// dialect reports the Code IR dialect clause of rule 2 that an import of b by a, both under
// internal/ir, breaks, or "".
func dialect(a, b string) string {
	const code = "internal/ir/code"
	switch {
	case a == code:
		if under(b, code) {
			return "internal/ir/code imports no dialect"
		}
	case under(a, code+"/flow"):
		if b != code && !under(b, "internal/ir/core") && !under(b, code+"/flow") {
			return "within internal/ir, code/flow imports only code and ir/core"
		}
	case under(a, code+"/action"):
		if b != code && !under(b, code+"/action") {
			return "within internal/ir, code/action imports only code"
		}
	case a == code+"/exec":
		if b != code {
			return "within internal/ir, code/exec imports only code"
		}
	case under(a, code+"/exec"):
		if b != code && !under(b, code+"/exec") && !under(b, code+"/action") {
			return "within internal/ir, the packages under code/exec import only code, code/exec and code/action"
		}
	}
	return ""
}

// A layer is a group of packages of the release layout that the layer graph orders.
type layer string

// The layers. The compiler-side layers follow the layer graph of the design; outside are the
// commands' neighbours that the graph does not order (benchmarks, examples and the language
// specification's tests).
const (
	layerRuntime  layer = "runtime"
	layerCmd      layer = "cmd"
	layerPublic   layer = "public tool API"
	layerLSP      layer = "lsp"
	layerDriver   layer = "driver"
	layerAnalysis layer = "analysis"
	layerBackend  layer = "back end"
	layerMiddle   layer = "middle end"
	layerFront    layer = "front end"
	layerIR       layer = "ir"
	layerPass     layer = "pass"
	layerGrammar  layer = "grammar AST"
	layerUtil     layer = "utility"
	layerTesting  layer = "testing"
	layerOutside  layer = "outside"
)

// layerOf returns the layer of the package at the layout path t.
func layerOf(t string) layer {
	switch {
	case runtimeSide(t):
		return layerRuntime
	case under(t, "cmd"):
		return layerCmd
	case under(t, "pkg/compiler"), under(t, "pkg/lint"), under(t, "pkg/sample"), under(t, "pkg/editfuzz"), under(t, "internal/fixture"):
		return layerPublic
	case under(t, "pkg/grammar/ast"):
		return layerGrammar
	case under(t, "internal/lsp"):
		return layerLSP
	case under(t, "internal/driver"):
		return layerDriver
	case under(t, "internal/analysis"):
		return layerAnalysis
	case under(t, "internal/backend"):
		return layerBackend
	case under(t, "internal/middleend"):
		return layerMiddle
	case under(t, "internal/frontend"), under(t, "internal/syntax/fmt"):
		return layerFront
	case under(t, "internal/ir"):
		return layerIR
	case under(t, "internal/pass"):
		return layerPass
	case under(t, "internal/diagnostic"), under(t, "internal/cancel"), under(t, "internal/cliflag"):
		return layerUtil
	case under(t, "internal/testing"):
		return layerTesting
	}
	return layerOutside
}

// layerArrows are the arrows of the layer graph: each layer imports the layers that it points
// to and, through them, every layer below. Every compiler-side layer may import the runtime
// side and, except the grammar AST, the utilities, which import only the grammar AST (the
// positions of diagnostics).
var layerArrows = map[layer][]layer{
	layerCmd:      {layerPublic, layerLSP},
	layerPublic:   {layerDriver},
	layerLSP:      {layerAnalysis},
	layerDriver:   {layerAnalysis},
	layerAnalysis: {layerBackend},
	layerBackend:  {layerMiddle, layerIR},
	layerMiddle:   {layerFront, layerIR},
	layerFront:    {layerIR, layerGrammar},
	layerIR:       {layerPass, layerGrammar},
	layerUtil:     {layerGrammar},
}

// layerImports reports whether a package of layer a may import one of layer b, a != b.
func layerImports(a, b layer) bool {
	switch {
	case a == layerTesting, a == layerOutside:
		return true // test support and the packages outside the graph may import any layer
	case b == layerRuntime, b == layerUtil && a != layerGrammar:
		return true // the grammar AST is below the utilities
	}
	seen := map[layer]bool{}
	var reach func(l layer) bool
	reach = func(l layer) bool {
		for _, n := range layerArrows[l] {
			if n == b {
				return true
			}
			if !seen[n] {
				seen[n] = true
				if reach(n) {
					return true
				}
			}
		}
		return false
	}
	return reach(a)
}

// dialectOf returns the Code IR dialect of the package at the layout path t, or "".
func dialectOf(t string) string {
	for _, d := range []string{"flow", "action", "exec"} {
		if under(t, "internal/ir/code/"+d) {
			return d
		}
	}
	return ""
}

// multiDialect reports whether the package at the layout path t may import more than one
// dialect: only the conversions of the middle end and the back end and test support may.
func multiDialect(t string) bool {
	return under(t, "internal/middleend/flowlower") || under(t, "internal/middleend/execlower") ||
		under(t, "internal/backend/vmlower") || under(t, "internal/testing")
}
