// placed is a package's place in the release layout.
type placed struct {
	target    string
	generated bool
	row       int // index of the layout row
}

// placeOf places the package at the module-relative path rel.
func placeOf(rel string) (placed, error) {
	best, bestLen := -1, -1
	var target string
	for i, p := range layout {
		base, tree := strings.CutSuffix(p.pkg, "/...")
		var t string
		switch {
		case rel == base:
			t = p.target
		case tree && strings.HasPrefix(rel, base+"/"):
			t = p.target + rel[len(base):]
		default:
			continue
		}
		n := len(base)
		if !tree {
			n++ // an exact row wins over a tree row of the same path
		}
		if n > bestLen {
			best, bestLen, target = i, n, t
		}
	}
	if best < 0 {
		return placed{}, fmt.Errorf("%s: no row of layout places the package; add one at its path in the release layout", rel)
	}
	return placed{target: target, generated: layout[best].generated, row: best}, nil
}

// under reports whether the layout path t is dir or below it.
func under(t, dir string) bool {
	return t == dir || strings.HasPrefix(t, dir+"/")
}

// runtimeSide reports whether the layout path t is on the runtime side.
func runtimeSide(t string) bool {
	return under(t, "pkg/runtime") || under(t, "pkg/bytecode") || under(t, "internal/runtime")
}

// publicRuntime reports whether t is a public package of the runtime side, where the chains of
// rule 1 start.
func publicRuntime(t string) bool {
	return under(t, "pkg/runtime") || under(t, "pkg/bytecode")
}

// golib is the layout path of the library of generated Go parsers.
const golib = "pkg/runtime/golib"

// libraryImport reports whether the library of generated Go parsers may import the package at
// the layout path t.
func libraryImport(t string) bool {
	switch t {
	case "pkg/runtime", "pkg/runtime/input", "pkg/runtime/value", "pkg/runtime/value/impl",
		"pkg/runtime/instrument", "pkg/runtime/schema":
		return true
	}
	return false
}

// engineSide reports whether t is a package that a generated parser must not link: the VM or
// the internal runtime.
func engineSide(t string) bool {
	return under(t, "pkg/runtime/vm") || under(t, "internal/runtime")
}

// layer2 reports the rule 2 clauses that an import of the package at layout path b by the
// package at layout path a breaks.
func layer2(a, b string) []string {
	if a == b {
		return nil
	}
	var broken []string
	if under(a, "internal/pass") && !under(b, "internal/pass") {
		broken = append(broken, "internal/pass imports nothing of the module")
	}
	if under(a, "internal/ir") {
		if !under(b, "internal/ir") && !under(b, "internal/pass") && !under(b, "internal/cancel") && b != "pkg/grammar" {
			broken = append(broken, "internal/ir/** imports only internal/ir/**, internal/pass, internal/cancel and pkg/grammar")
		} else if under(b, "internal/ir") {
			if c := dialect(a, b); c != "" {
				broken = append(broken, c)
			}
		}
	}
	for _, l := range []struct {
		dir   string
		not   []string
		label string
	}{
		{"internal/frontend", []string{"internal/middleend", "internal/backend", "internal/analysis", "internal/lsp"}, "the front end imports no middle end, back end, analysis or LSP package"},
		{"internal/middleend", []string{"internal/backend", "internal/analysis", "internal/lsp"}, "the middle end imports no back end, analysis or LSP package"},
		{"internal/backend", []string{"internal/analysis", "internal/lsp"}, "the back end imports no analysis or LSP package"},
	} {
		if !under(a, l.dir) {
			continue
		}
		for _, n := range l.not {
			if under(b, n) {
				broken = append(broken, l.label)
				break
			}
		}
	}
	if under(b, "internal/lsp") && !under(a, "internal/lsp") && !under(a, "cmd") && !under(a, "internal/testing") {
		broken = append(broken, "only cmd/** and internal/testing/** import internal/lsp/**")
	}
	if under(b, "internal/testing") && !under(a, "internal/testing") {
		broken = append(broken, "only internal/testing/** imports internal/testing/** outside tests")
	}
	return broken
}

// dialect reports the Code IR dialect clause of rule 2 that an import of b by a, both under
// internal/ir, breaks, or "".
func dialect(a, b string) string {
	const code = "internal/ir/code"
	switch {
	case a == code:
		if under(b, code) {
			return "internal/ir/code imports no dialect"
		}
	case under(a, code+"/flow"):
		if b != code && !under(b, "internal/ir/core") && !under(b, code+"/flow") {
			return "within internal/ir, code/flow imports only code and ir/core"
		}
	case under(a, code+"/action"):
		if b != code && !under(b, code+"/action") {
			return "within internal/ir, code/action imports only code"
		}
	case a == code+"/exec":
		if b != code {
			return "within internal/ir, code/exec imports only code"
		}
	case under(a, code+"/exec"):
		if b != code && !under(b, code+"/exec") && !under(b, code+"/action") {
			return "within internal/ir, the packages under code/exec import only code, code/exec and code/action"
		}
	}
	return ""
}
