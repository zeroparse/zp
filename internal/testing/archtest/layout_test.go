// A place puts the packages of the module at a path of the release layout, the path the rules
// are stated on.
type place struct {
	// pkg is a package path relative to the module. With a "/..." suffix the row places the
	// package and every package below it, at target followed by the rest of the path. The longest
	// row that matches a package places it.
	pkg string
	// target is the path of the package in the release layout. A package that the layout splits
	// is placed where the part that keeps its imports goes; its row says where the rest goes.
	target string
	// generated marks a parser generated by zp gen, which rule 1a checks.
	generated bool
}

