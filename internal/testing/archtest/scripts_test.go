// The tests below run the repository scripts (hack/check-commits.sh, .agents/scripts) against a
// temporary repository and a temporary bare remote. They never touch this repository or the
// real queue.

func scriptEnv(t *testing.T, state string) []string {
	t.Helper()
	return append(os.Environ(),
		"ZP_AGENT_STATE="+state, "BENCHLOCK_POLL=1",
		"GIT_AUTHOR_NAME=t", "GIT_AUTHOR_EMAIL=t@example.com",
		"GIT_COMMITTER_NAME=t", "GIT_COMMITTER_EMAIL=t@example.com",
		"GIT_CONFIG_GLOBAL=/dev/null", "GIT_CONFIG_SYSTEM=/dev/null")
}

func runIn(t *testing.T, dir string, env []string, name string, args ...string) (string, error) {
	t.Helper()
	cmd := exec.Command(name, args...)
	cmd.Dir = dir
	cmd.Env = env
	out, err := cmd.CombinedOutput()
	return string(out), err
}

func mustRun(t *testing.T, dir string, env []string, name string, args ...string) string {
	t.Helper()
	out, err := runIn(t, dir, env, name, args...)
	if err != nil {
		t.Fatalf("%s %v: %v\n%s", name, args, err, out)
	}
	return out
}

func needTools(t *testing.T) {
	t.Helper()
	for _, tool := range []string{"git", "bash", "perl"} {
		if _, err := exec.LookPath(tool); err != nil {
			t.Skipf("%s is not installed", tool)
		}
	}
}

func write(t *testing.T, path, content string, mode os.FileMode) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), mode); err != nil {
		t.Fatal(err)
	}
}

func TestCheckCommitsClosingTrailers(t *testing.T) {
	needTools(t)
	root, err := filepath.Abs(filepath.Join("..", "..", ".."))
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	env := scriptEnv(t, t.TempDir())
	mustRun(t, dir, env, "git", "init", "-q", "-b", "main")
	write(t, filepath.Join(dir, "a"), "a", 0o644)
	mustRun(t, dir, env, "git", "add", "a")
	mustRun(t, dir, env, "git", "commit", "-q", "-m", "Seed", "-m", "Initial.")
	mustRun(t, dir, env, "git", "checkout", "-q", "-b", "feat/x")
	script := filepath.Join(root, "hack", "check-commits.sh")
	for _, c := range []struct {
		subject, body string
		bad           bool
	}{
		{"Stabilize the flaky tests", "Fix 3 flaky tests in the engine.", false},
		{"Fix 3 flaky tests", "They failed under load.", false},
		{"Rework the prefix handling", "This resolves nothing about issue numbering.", false},
		{"Rework the cache", "Closes #12", true},
		{"Rework the cache", "Closes zeroparse/zp#1", true},
		{"Rework the cache", "fixes: #7", true},
		{"Rework the cache", "Resolved owner/repo#3", true},
	} {
		mustRun(t, dir, env, "git", "commit", "-q", "--allow-empty", "-m", c.subject, "-m", c.body)
		out, err := runIn(t, dir, env, "bash", script, "HEAD~1", "HEAD")
		if (err != nil) != c.bad {
			t.Errorf("subject %q body %q: bad=%v, got err=%v\n%s", c.subject, c.body, c.bad, err, out)
		}
	}
}

// The attribution check matches footers, not prose: a body may say that a parser was generated
// with an option.
func TestCheckCommitsAttribution(t *testing.T) {
	needTools(t)
	root, err := filepath.Abs(filepath.Join("..", "..", ".."))
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	env := scriptEnv(t, t.TempDir())
	mustRun(t, dir, env, "git", "init", "-q", "-b", "main")
	write(t, filepath.Join(dir, "a"), "a", 0o644)
	mustRun(t, dir, env, "git", "add", "a")
	mustRun(t, dir, env, "git", "commit", "-q", "-m", "Seed", "-m", "Initial.")
	mustRun(t, dir, env, "git", "checkout", "-q", "-b", "feat/x")
	script := filepath.Join(root, "hack", "check-commits.sh")
	for _, c := range []struct {
		name, body string
		bad        bool
	}{
		{"prose", "A parser generated with -lib embed carries the library.", false},
		{"prose, capitalized, at the start of a line", "Generated with the option, a parser\nkeeps the library.", false},
		{"footer", "Rework the cache.\n\n\U0001F916 Generated with [Claude Code](https://claude.com/claude-code)", true},
		{"footer without the robot", "Rework the cache.\n\nGenerated with [Claude Code](https://claude.com/claude-code)", true},
		{"footer by", "Rework the cache.\n\nGenerated by [a tool](https://example.com)", true},
		{"co-author", "Rework the cache.\n\nCo-Authored-By: Claude <noreply@anthropic.com>", true},
	} {
		mustRun(t, dir, env, "git", "commit", "-q", "--allow-empty", "-m", "Rework the cache", "-m", c.body)
		out, err := runIn(t, dir, env, "bash", script, "HEAD~1", "HEAD")
		if (err != nil) != c.bad {
			t.Errorf("%s: bad=%v, got err=%v\n%s", c.name, c.bad, err, out)
		}
	}
}

// stubGate stands in for hack/gate.sh: it records the levels, and GATE_MODE=kill makes it die
// after one passing step, as a gate killed by benchstop or a reboot does.
const stubGate = `#!/usr/bin/env bash
lv=
while [ $# -gt 0 ]; do case $1 in --summary) sum=$2; shift 2;; --base) shift 2;; *) lv="$lv $1"; shift;; esac; done
printf 'vet\texit 0\t0s\n' > "$sum"
[ "${GATE_MODE:-}" = kill ] && kill -9 $$
printf 'test\texit 0\t1s\n' >> "$sum"
echo "levels:$lv"
`

func TestTrainLandRequiresACompletedGate(t *testing.T) {
	needTools(t)
	root, err := filepath.Abs(filepath.Join("..", "..", ".."))
	if err != nil {
		t.Fatal(err)
	}
	tmp := t.TempDir()
	state := filepath.Join(tmp, "state")
	env := scriptEnv(t, state)
	remote := filepath.Join(tmp, "o.git")
	mustRun(t, tmp, env, "git", "init", "-q", "--bare", "-b", "main", remote)
	w := filepath.Join(tmp, "w")
	mustRun(t, tmp, env, "git", "clone", "-q", remote, w)
	for _, name := range []string{"lib.sh", "benchlock.sh", "testslot.sh", "run-gate.sh", "train.sh"} {
		b, err := os.ReadFile(filepath.Join(root, ".agents", "scripts", name))
		if err != nil {
			t.Fatal(err)
		}
		write(t, filepath.Join(w, ".agents", "scripts", name), string(b), 0o755)
	}
	b, err := os.ReadFile(filepath.Join(root, "hack", "check-commits.sh"))
	if err != nil {
		t.Fatal(err)
	}
	write(t, filepath.Join(w, "hack", "check-commits.sh"), string(b), 0o755)
	write(t, filepath.Join(w, "hack", "gate.sh"), stubGate, 0o755)
	mustRun(t, w, env, "git", "checkout", "-q", "-b", "main")
	mustRun(t, w, env, "git", "add", ".")
	mustRun(t, w, env, "git", "commit", "-q", "-m", "Seed", "-m", "Initial.")
	mustRun(t, w, env, "git", "push", "-q", "origin", "main")

	branch := func(name, file string) {
		mustRun(t, w, env, "git", "checkout", "-q", "-b", name, "main")
		write(t, filepath.Join(w, file), name, 0o644)
		mustRun(t, w, env, "git", "add", file)
		mustRun(t, w, env, "git", "commit", "-q", "-m", "Add "+file, "-m", "The test needs it.")
	}
	branch("feat/code", "internal/runtime/engine/x.go")
	branch("feat/doc", "docs/a.md")
	train := filepath.Join(w, ".agents", "scripts", "train.sh")
	step := func(wantOK bool, genv []string, args ...string) string {
		t.Helper()
		out, err := runIn(t, w, append(env, genv...), "bash", append([]string{train}, args...)...)
		if (err == nil) != wantOK {
			t.Fatalf("train.sh %v: err=%v, want ok=%v\n%s", args, err, wantOK, out)
		}
		return out
	}

	step(true, nil, "stack", "c1", "feat/code")
	// A gate that was killed after a passing step leaves a partial all-pass summary: no landing.
	step(false, []string{"GATE_MODE=kill"}, "gate", "c1")
	if out := step(false, nil, "land", "c1"); !strings.Contains(out, "no completed gate") {
		t.Errorf("land after a killed gate: %s", out)
	}
	// A docs gate on a stack with code is not enough.
	step(true, nil, "gate", "c1", "docs")
	if out := step(false, nil, "land", "c1"); !strings.Contains(out, "needs the gate level engine") {
		t.Errorf("land after a docs gate on code: %s", out)
	}
	// An engine path needs engine and full: the default levels cover them.
	step(true, nil, "gate", "c1", "engine")
	if out := step(false, nil, "land", "c1"); !strings.Contains(out, "needs the gate level full") {
		t.Errorf("land after an engine gate on engine paths: %s", out)
	}
	if out := step(true, nil, "gate", "c1"); !strings.Contains(out, "engine full") {
		t.Errorf("default levels of an engine stack: %s", out)
	}
	step(true, nil, "land", "c1")
	if got := mustRun(t, w, env, "git", "--git-dir", remote, "log", "--format=%s", "main"); !strings.Contains(got, "Add internal/runtime/engine/x.go") {
		t.Errorf("main does not hold the landed commit:\n%s", got)
	}

	// A stack of documentation needs only docs.
	step(true, nil, "stack", "d1", "feat/doc")
	if out := step(true, nil, "gate", "d1"); !strings.Contains(out, "gated") || strings.Contains(out, "engine") {
		t.Errorf("default levels of a docs stack: %s", out)
	}
	step(true, nil, "land", "d1")

	// A file moved out of an engine path still counts as a change of that path.
	mustRun(t, w, env, "git", "fetch", "-q", "origin")
	mustRun(t, w, env, "git", "checkout", "-q", "-b", "feat/mv", "origin/main")
	mustRun(t, w, env, "git", "mv", "internal/runtime/engine/x.go", "docs/moved.md")
	mustRun(t, w, env, "git", "commit", "-q", "-m", "Move x out of the engine", "-m", "The test needs it.")
	step(true, nil, "stack", "m1", "feat/mv")
	if out := step(true, nil, "gate", "m1"); !strings.Contains(out, "engine full") {
		t.Errorf("default levels of a stack that moves a file out of the engine: %s", out)
	}
}

// The scripts that use the state directory stop when ZP_AGENT_STATE is unset or relative, before
// they create anything: a default would let a lane that forgot it run a private queue beside the
// shared one. push-branch.sh does not use the state and does not ask for it.
func TestScriptsRequireAgentState(t *testing.T) {
	needTools(t)
	home := t.TempDir()
	var base []string
	for _, kv := range os.Environ() {
		if !strings.HasPrefix(kv, "ZP_AGENT_STATE=") && !strings.HasPrefix(kv, "HOME=") && !strings.HasPrefix(kv, "XDG_STATE_HOME=") {
			base = append(base, kv)
		}
	}
	base = append(base, "HOME="+home, "BENCHLOCK_POLL=1")
	src, err := filepath.Abs(filepath.Join("..", "..", "..", ".agents", "scripts"))
	if err != nil {
		t.Fatal(err)
	}
	// The scripts run from a copy in a scratch repository, so that a script that does not stop
	// acts on the scratch repository and not on this one.
	root := filepath.Join(t.TempDir(), "w")
	names, _ := filepath.Glob(filepath.Join(src, "*.sh"))
	for _, n := range names {
		b, err := os.ReadFile(n)
		if err != nil {
			t.Fatal(err)
		}
		write(t, filepath.Join(root, ".agents", "scripts", filepath.Base(n)), string(b), 0o755)
	}
	gitEnv := scriptEnv(t, t.TempDir())
	mustRun(t, root, gitEnv, "git", "init", "-q", "-b", "main")
	mustRun(t, root, gitEnv, "git", "add", ".")
	mustRun(t, root, gitEnv, "git", "commit", "-q", "-m", "Seed")
	scripts := map[string][]string{
		"benchlock.sh": {"t", "true"}, "testslot.sh": {"true"}, "run-gate.sh": {"code"},
		"queue-status.sh": nil, "benchstop.sh": {"t"}, "lane-new.sh": {"x", "fix/x"},
		"ready.sh": {"scope", "checks"}, "train.sh": {"stack", "x"}, "alpha-check.sh": nil,
	}
	for _, state := range []string{"", "relative/state"} {
		env := base
		if state != "" {
			env = append(append([]string{}, base...), "ZP_AGENT_STATE="+state)
		}
		for name, args := range scripts {
			out, err := runIn(t, root, env, "bash", append([]string{filepath.Join(root, ".agents", "scripts", name)}, args...)...)
			if err == nil || !strings.Contains(out, "ZP_AGENT_STATE") {
				t.Errorf("%s with ZP_AGENT_STATE=%q: err %v, output %q; want a stop that names ZP_AGENT_STATE", name, state, err, out)
			}
		}
	}
	if entries, _ := os.ReadDir(home); len(entries) != 0 {
		t.Errorf("the scripts created %v in HOME", entries)
	}
	if _, err := os.Stat(filepath.Join(root, "relative")); err == nil {
		t.Errorf("the scripts created relative/ in the repository")
	}
	out, _ := runIn(t, root, base, "bash", filepath.Join(root, ".agents", "scripts", "push-branch.sh"))
	if strings.Contains(out, "ZP_AGENT_STATE") {
		t.Errorf("push-branch.sh asks for ZP_AGENT_STATE: %q", out)
	}
}

// TestGateDocsDetection runs the planning of hack/gate.sh (--dry-run docs) in a scratch repository.
// A change list longer than a pipe buffer whose first line is under docs/ must plan the site steps:
// detection that pipes the list into grep -q under pipefail dies of SIGPIPE there and skipped them.
// A change outside the site paths skips them, and a base that git cannot diff against plans them.
func TestGateDocsDetection(t *testing.T) {
	needTools(t)
	b, err := os.ReadFile(filepath.Join("..", "..", "..", "hack", "gate.sh"))
	if err != nil {
		t.Fatal(err)
	}
	w := t.TempDir()
	env := append(scriptEnv(t, t.TempDir()), "GATE_AFFECTED_CMD=true")
	write(t, filepath.Join(w, "hack", "gate.sh"), string(b), 0o755)
	mustRun(t, w, env, "git", "init", "-q", "-b", "main")
	mustRun(t, w, env, "git", "add", ".")
	mustRun(t, w, env, "git", "commit", "-q", "-m", "Seed")
	base := strings.TrimSpace(mustRun(t, w, env, "git", "rev-parse", "HEAD"))

	plan := func(base string) string {
		t.Helper()
		return mustRun(t, w, env, "bash", filepath.Join(w, "hack", "gate.sh"), "--base", base, "--dry-run", "docs")
	}
	planned := func(out string) bool {
		t.Helper()
		test := strings.Contains(out, "site-test       cd site")
		build := strings.Contains(out, "site-build      site/build.sh")
		if test != build {
			t.Fatalf("site-test and site-build disagree:\n%s", out)
		}
		return test
	}

	write(t, filepath.Join(w, "code", "a.go"), "package a\n", 0o644)
	mustRun(t, w, env, "git", "add", "code")
	mustRun(t, w, env, "git", "commit", "-q", "-m", "Code")
	if out := plan(base); planned(out) {
		t.Errorf("a change outside docs/, spec/, site/ and README.md plans the site steps:\n%s", out)
	}

	write(t, filepath.Join(w, "docs", "a.md"), "# A\n", 0o644)
	long := strings.Repeat("x", 60)
	for i := range 3000 {
		write(t, filepath.Join(w, "zz", long+strconv.Itoa(i)), "", 0o644)
	}
	mustRun(t, w, env, "git", "add", "docs", "zz")
	mustRun(t, w, env, "git", "commit", "-q", "-m", "Docs")
	if n := len(mustRun(t, w, env, "git", "diff", "--name-only", base, "HEAD")); n < 1<<17 {
		t.Fatalf("the change list has %d bytes; it must exceed a pipe buffer", n)
	}
	if out := plan(base); !planned(out) {
		t.Errorf("a long change list that touches docs/ skips the site steps:\n%s", out)
	}
	if out := plan(strings.Repeat("0", 40)); !planned(out) {
		t.Errorf("a base that cannot be diffed skips the site steps:\n%s", out)
	}
}

// TestAffectedTestsDeletedPackages runs hack/affected-tests.sh in a scratch module whose change deletes a
// package that the base had. The set lists only packages that exist at the head: go test fails on the
// deleted one ("no required module provides package"), although the script's own rules (the generated-program
// packages that a pkg/runtime change selects) name it. A package that imported it at the base and still exists
// is listed, and a go list that fails fails the script instead of emptying the set.
func TestAffectedTestsDeletedPackages(t *testing.T) {
	needTools(t)
	for _, tool := range []string{"go", "python3"} {
		if _, err := exec.LookPath(tool); err != nil {
			t.Skipf("%s is not installed", tool)
		}
	}
	b, err := os.ReadFile(filepath.Join("..", "..", "..", "hack", "affected-tests.sh"))
	if err != nil {
		t.Fatal(err)
	}
	w := t.TempDir()
	env := append(scriptEnv(t, t.TempDir()), "GOFLAGS=-mod=mod", "GOWORK=off", "GOTOOLCHAIN=local")
	const mod = "zeroparse.dev/zp"
	write(t, filepath.Join(w, "hack", "affected-tests.sh"), string(b), 0o755)
	write(t, filepath.Join(w, "go.mod"), "module "+mod+"\n\ngo 1.21\n", 0o644)
	write(t, filepath.Join(w, "pkg", "runtime", "libgo", "g.go"), "package libgo\n", 0o644)
	write(t, filepath.Join(w, "codegen", "c.go"), "package codegen\n", 0o644)
	write(t, filepath.Join(w, "user", "u.go"), "package user\n\nimport _ \""+mod+"/codegen\"\n", 0o644)
	write(t, filepath.Join(w, "dep", "d.go"), "package dep\n\nimport _ \""+mod+"/pkg/runtime/libgo\"\n", 0o644)
	mustRun(t, w, env, "git", "init", "-q", "-b", "main")
	mustRun(t, w, env, "git", "add", ".")
	mustRun(t, w, env, "git", "commit", "-q", "-m", "Seed")
	base := strings.TrimSpace(mustRun(t, w, env, "git", "rev-parse", "HEAD"))

	// The change deletes codegen, drops user's import of it and touches the runtime library.
	mustRun(t, w, env, "git", "rm", "-q", "-r", "codegen")
	write(t, filepath.Join(w, "user", "u.go"), "package user\n", 0o644)
	write(t, filepath.Join(w, "pkg", "runtime", "libgo", "g.go"), "package libgo\n\nconst X = 1\n", 0o644)
	mustRun(t, w, env, "git", "add", "-u")
	mustRun(t, w, env, "git", "commit", "-q", "-m", "Delete codegen")

	out := mustRun(t, w, env, "sh", filepath.Join(w, "hack", "affected-tests.sh"), base, "HEAD")
	got := map[string]bool{}
	for _, l := range strings.Fields(out) {
		got[l] = true
	}
	if got[mod+"/codegen"] {
		t.Errorf("the deleted package is listed:\n%s", out)
	}
	for _, p := range []string{"user", "dep", "pkg/runtime/libgo"} {
		if !got[mod+"/"+p] {
			t.Errorf("%s still exists at the head and is affected, but is not listed:\n%s", p, out)
		}
	}
	for l := range got {
		if strings.HasPrefix(l, mod) {
			mustRun(t, w, env, "go", "list", l)
		}
	}

	// A head whose packages cannot be listed fails the script; it does not print an empty set.
	write(t, filepath.Join(w, "go.mod"), "module "+mod+"\n\ngo 1.21\nbogus\n", 0o644)
	if out, err := runIn(t, w, env, "sh", filepath.Join(w, "hack", "affected-tests.sh"), base, "HEAD"); err == nil {
		t.Errorf("a failing go list succeeded with %q", out)
	}
}
